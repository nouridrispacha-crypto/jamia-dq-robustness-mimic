"""Heatmaps and contrast figures, with the standardised binary arm and the 90-day survival.

Deliberately narrower than regen_figures: that script also calls make_s2_grid.main() with its
default arguments, which are portrait with shading, and that is the very mistake regen_grids
exists to undo. The three grids were already regenerated by regen_grids at the published
landscape size, so they are left alone here.

What remains are the three heatmaps and the three per-outcome contrast figures. The binary
file map is repointed at the standardised inputs as the other regen scripts do; the survival
map already points at the relaunch.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from config import PAPER
import runpy
import sys
from datetime import datetime
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
P = Path(PAPER)
sys.path.insert(0, str(P))
IN = Path(__file__).resolve().parent / "scaled_inputs"

import analyse_stats_v2 as V2

for dim in V2.BINARY.file_map:
    for scen in V2.BINARY.file_map[dim]:
        p = IN / dim / f"{scen}.csv"
        assert p.exists(), p
        V2.BINARY.file_map[dim][scen] = p
print("binaire -> standardise")
print("survie  -> {}".format(Path(V2.SURVIVAL.file_map["coherence"]["S2"]).parents[2].name))
print("continu -> inchange\n")

TARGETS = ["figure6_heatmap_s2", "suppfig9_heatmap_s1", "suppfig10_heatmap_s3",
           "suppfig10_contrasts_binary", "suppfig11_contrasts_continuous",
           "suppfig12_contrasts_survival", "figure6_contrasts_main"]
t0 = datetime.now().timestamp()

print("=== cartes de chaleur ===")
import make_supp_heatmaps as H
if hasattr(H, "_cache"):
    H._cache.clear()
runpy.run_path(str(P / "make_supp_heatmaps.py"), run_name="__main__")

print("\n=== figures de contrastes ===")
import make_s2_grid as G
for c in (G._cache, G._lead_cache, G._model_cache):
    c.clear()
runpy.run_path(str(P / "make_contrast_figure.py"), run_name="__main__")

print("\n=== etat des fichiers ===")
for name in TARGETS:
    f = P / "img" / f"{name}.pdf"
    if not f.exists():
        print("  {:34s} ABSENT".format(name))
        continue
    tag = "REECRIT " if f.stat().st_mtime >= t0 else "inchange"
    print("  {:34s} {} {:7.0f} Ko".format(name, tag, f.stat().st_size / 1024))
print("\nles trois grilles ne sont pas touchees ici : regen_grids les a deja refaites")
